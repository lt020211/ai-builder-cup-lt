/**
 * 提示词。
 *
 * ────────────────────────────────────────────────────────────────────────
 * 这份提示词要守住三条纪律，每条都对应代码里的一处防线
 * ────────────────────────────────────────────────────────────────────────
 *   1. **数字必须来自工具** —— 提示词里要求，代码里也不给模型任何可编的余地
 *      （estimate_memory / check_compat 都是精确计算，模型算不出来）
 *   2. **风险等级不可协商** —— 提示词说清楚"你没权限定级"，代码里 action_id
 *      之外根本没有 risk 字段可传（tools.js 的参数白名单）
 *   3. **查不到就说查不到** —— 知识库只有 24 个 Xid；查不到时工具返回
 *      「无记录，不得推测」，提示词也明确要求如实说不知道
 *
 * 为什么这些要同时写在提示词和代码里：只写在提示词里是**可以被说服的**，
 * 只写在代码里模型会因为不理解边界而反复撞墙。两边都要有，但**最终生效的是代码**。
 *
 * ────────────────────────────────────────────────────────────────────────
 * 两个模式
 * ────────────────────────────────────────────────────────────────────────
 *   buildCasePrompt    单次分诊：用户贴了一段失败现场，判断「代码的锅还是该换卡」
 *   buildPatrolPrompt  值班巡检：不等人贴日志，自己去集群里发现问题、处置、触达
 *
 * 区别不在措辞，而在**任务边界**：单次分诊只需要给出判断，值班巡检还要去动手
 * （执行低风险动作）和去触达（建工单、通知人）。把这两件事混在一份提示词里，
 * 模型会在"贴了日志"的场景里也去尝试扫描整个集群。
 */

