const DIAGNOSTIC_DISCIPLINE = `【必须遵守的分诊纪律】

· 首发原则：日志里爆发大量 Xid 时，先定位**时间最早的那一条（T0）**。
  后面的往往是它的连锁反应。从中间任意一条入手，都会追错方向。

· 症状 ≠ 根因：同一句报错可以对应完全不同的根因。
  下结论前先问自己「同样这句话，还有别的解释吗？」
  例：「nvidia-smi 无法与驱动通信」至少有五种成因，其中只有一种是硬件故障。

· 趋势优先于快照：同一个 Xid，**单次出现**与**频次上升**是两件事，结论可能完全相反。
  一定要看 history_30d 与 ECC 趋势，不要只看最近一条事件。

· 因果关联：Xid 45 / 154 这类码本身不是根因，是前序错误的后果。
  看到它们必须回查触发它们的更早事件。

· 不要混为一谈：外观相似的报错成因可能完全不同
  （例如「驱动/库版本不匹配」与「无法与驱动通信」，修法一个在内核模块、一个在容器）。

· 应用故障不要走报修：把板子判给硬件之前，先排除代码与配置。
  报修是不可逆的资源决策 —— 走一次 RMA，集群就少一块卡。

· 注意「**有条件的**处置」：知识库里有些条目的升级动作是带前提的
  （典型措辞是「若与某个码同现」「若反复出现，才升级为硬件方向」）。
  看到这种条目，必须把前提**核对一遍**再下结论 —— 前提不成立就不要升级。
  ★ 看到错误码就直接给动作，是这类分诊里最典型的**过激反应**，
  代价是把一张还能用的卡送去报修，和把好卡下线是同一种错误。`;

const OUTPUT_FORMAT = `【输出要求】

先用一两句话给出**一句话结论**（分类 + 该不该报修），再展开。

展开时必须包含这四项，缺一不可：
  1. 故障分类：application / hardware / hardware_watch / environment / config / network / undetermined
  2. 是否报修：明确的是或否。这是运维最需要的一个判断，不许回避或含糊。
  3. 置信度：0-1。证据不足时必须如实给低值，不要为了显得笃定而凑高。
  4. 因果链：不是复述报错，而是「因为 A，所以 B，因此表现为 C」的链条。

每条结论后面标注支撑它的工具调用编号（如 T2、T5）。只能引用工具返回值里
真实出现过的 ref —— 系统会核对，编造的引用会被丢弃并记录。

最后单列一小节「还不确定的」，写清楚**哪些信息你拿不到**、拿到后能改变什么判断。
一个说得出自己边界的结论，比一个面面俱到的结论可信得多。`;

/** 把动作库渲染成模型可选的清单。★ 排除被标记「不建议」的动作。 */
function renderActionCatalog() {
  const lines = ACTION_LIST.map(
    (a) => `  ${a.id}｜${a.label}｜${RISK_LEVELS[a.risk].label}｜影响面：${a.affects}`,
  );
  const avoided = Object.values(DISCOURAGED_ACTIONS).map(
    (d) => `  ${d.id}｜${d.label} —— 系统已标记为「不建议」：${d.reason}`,
  );
  return [
    '【修复动作库（只能从这里选，传 action_id）】',
    ...lines,
    '',
    '另有以下动作**被系统明确标记为不建议，你不得推荐、也不得选用**：',
    ...avoided,
    '  （如果确实认为是这一类问题，应指出根因方向，让运维去查链路，而不是建议调大超时。）',
  ].join('\n');
}

const RISK_EXPLAINER = `【风险等级是怎么定的（你不需要判断，只需要知道）】

  低风险：只影响当前任务进程、可逆、不碰硬件与系统 → 系统可自主执行
  中风险：影响节点上其他任务，或需要短暂中断       → 必须人工逐条批准 + 勾选影响面
  高风险：不可逆、涉硬件资产、跨节点               → 必须人工批准 + 填写变更单号

★ 这个等级由动作库写死，你无法修改。判断依据是**爆炸半径**，不是难易：
  装个 wheel 可能很麻烦，但它只影响一个容器，所以是低风险；
  重启节点只是敲一行命令，但它会杀掉别人跑了一周的任务，所以是中风险。`;

