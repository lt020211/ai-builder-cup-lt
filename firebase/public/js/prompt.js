function dump(v) {
  return JSON.stringify(v, null, 2);
}

/**
 * 单次分诊的提示词。
 *
 * @param evidence  证据包（已归一化）
 * @param pre       预分析结果（代码确证的事实）
 * @param hints     预分析的倾向性提示（明确标注为提示而非结论）
 */
export function buildCasePrompt(evidence, pre, hints = []) {
  const sections = [
    ROLE,
    '',
    hardRules('case'),
    '',
    DIAGNOSTIC_DISCIPLINE,
    '',
    renderActionCatalog(),
    '',
    RISK_EXPLAINER,
    '',
    CASE_TASK,
    '',
    OUTPUT_FORMAT,
    '',
    '────────────────────────────────────────',
    '【本次现场】',
    '',
    `案例：${evidence.title || '（未命名）'}`,
    `节点：${evidence.job?.node || '未知'}　卡型：${evidence.job?.gpu_type || '未知'}`,
    '',
    '报错原文：',
    '```',
    String(evidence.stderr_excerpt || '（无）').slice(0, 4000),
    '```',
    '',
    '环境与训练配置：',
    '```json',
    dump({
      environment: evidence.environment,
      training_config: evidence.training_config,
      docker_image: evidence.docker_image || null,
    }),
    '```',
    '',
    '【已确证事实（由确定性代码算出，无需你重新计算）】',
    '```json',
    dump(pre?.confirmed || {}),
    '```',
  ];

  if (hints.length) {
    sections.push(
      '',
      '【倾向性提示（★ 这是机器投票的结果，不是结论）】',
      '```json',
      dump(hints),
      '```',
      '注意：这只是一个起点。若你调取的证据与之冲突，**以证据为准**，并在结论里说明为什么。',
    );
  }

  return sections.join('\n');
}

/**
 * 值班巡检的提示词。
 *
 * @param clusterMeta  集群元信息（节点数、集群名等）
 * @param now          当前时间字符串，注入进去让模型知道"现在几点"——
 *                     判断"劣化速度"需要时间基准，模型自己的时间感不可靠。
 */
export function buildPatrolPrompt(clusterMeta = {}, now = null) {
  const stamp = now || new Date().toISOString();
  return [
    ROLE,
    '',
    hardRules('patrol'),
    '',
    DIAGNOSTIC_DISCIPLINE,
    '',
    renderActionCatalog(),
    '',
    RISK_EXPLAINER,
    '',
    PATROL_TASK,
    '',
    OUTPUT_FORMAT,
    '',
    '────────────────────────────────────────',
    '【本次巡查范围】',
    `集群：${clusterMeta.name || '演示集群（模拟节点，非生产环境）'}`,
    `节点数：${clusterMeta.node_count ?? '未知'}`,
    `当前时间：${stamp}`,
    '',
    '提醒：你没有收到任何报错。要发现什么，必须先去看。',
    '第一步就调用 scan_cluster。',
  ].join('\n');
}

